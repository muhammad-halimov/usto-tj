<?php

namespace App\Service\Extra;

use Symfony\Component\Uid\Uuid;

/**
 * БАГФИКС (06.09.2026, переход всех сущностей на UUID-первичные ключи) —
 * везде, где раньше сравнивали два int-ID через ===/!== (getId() !==
 * getId()), теперь нельзя делать так же: Uuid — объект-значение, ===/!==
 * у объектов в PHP всегда сравнивает ИДЕНТИЧНОСТЬ (тот же самый инстанс в
 * памяти), а не значение. Doctrine identity map ЧАСТО возвращает один и
 * тот же PHP-объект для одной и той же строки в БД в рамках одного
 * EntityManager, но полагаться на это для корректности нельзя (например,
 * для ещё не сохранённой сущности, у которой Uuid только что сгенерирован
 * в памяти, но объект получен другим путём — гарантии одного инстанса
 * нет). Отсюда same() — единая точка сравнения "то же самое ли значение
 * ID", через Uuid::equals() (сравнение по строковому значению), а не по
 * ссылке.
 */
final class UuidUtil
{
    /**
     * true, если оба null (это тоже "совпадение" — семантика та же, что у
     * прежнего === для int: null === null было true), либо оба заданы и
     * представляют один и тот же UUID.
     */
    public static function same(?Uuid $a, ?Uuid $b): bool
    {
        if ($a === null || $b === null) {
            return $a === $b;
        }

        return $a->equals($b);
    }
}
