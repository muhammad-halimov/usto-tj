<?php

namespace App\Service\Extra;

use Symfony\Component\Uid\Uuid;

/**
 * БАГФИКС (06.09.2026, переход всех сущностей на UUID-первичные ключи) —
 * везде, где раньше сравнивали два int-ID через ===/!== (getId() !==
 * getId()), теперь нельзя делать так же: Uuid — объект-значение, ===/!==
 * у объектов в PHP всегда сравнивает ИДЕНТИЧНОСТЬ (тот же самый инстанс в
 * памяти), а не значение. Doctrine identity map ЧАСТО возвращает один и
 * тот же PHP-объект для одной и той же строки в БД в рамках одного
 * EntityManager, но полагаться на это для корректности нельзя (например,
 * для ещё не сохранённой сущности, у которой Uuid только что сгенерирован
 * в памяти, но объект получен другим путём — гарантии одного инстанса
 * нет). Отсюда same() — единая точка сравнения "то же самое ли значение
 * ID", через Uuid::equals() (сравнение по строковому значению), а не по
 * ссылке.
 */
final class UuidUtil
{
    /**
     * true, если оба null (это тоже "совпадение" — семантика та же, что у
     * прежнего === для int: null === null было true), либо оба заданы и
     * представляют один и тот же UUID.
     */
    public static function same(?Uuid $a, ?Uuid $b): bool
    {
        if ($a === null || $b === null) {
            return $a === $b;
        }

        return $a->equals($b);
    }

    /**
     * Короткий, читаемый "тег" ID для __toString() (07.09.2026, по жалобе
     * на переполох в листингах EasyAdmin) — раньше "#$this->id ..." давало
     * "#42 Название", теперь с UUID дало бы "#01a07887-5622-7dd0-9854-
     * e13224fe... Название" — 36 символов чистого шума вместо короткого
     * узнаваемого тега, и именно это распирало колонки в EasyAdmin
     * (CollectionField/AssociationField рендерят __toString() каждого
     * элемента списком, длинная строка обрезается спереди же настройками
     * колонки, так что даже название переставало быть видно).
     *
     * substr(..., 0, 8) — первые 8 hex-символов UUID (у UuidV7 это часть
     * таймстемпа, не случайные байты — у сущностей, созданных с разницей в
     * секунды, эти 8 символов почти наверняка совпадут, это ОЖИДАЕМО: не
     * идентификатор в строгом смысле, чисто визуальный якорь в
     * человекочитаемой строке, тот же принцип, что у короткого git-хэша
     * коммита). Настоящий, однозначный ID — через getId(), __toString()
     * никогда не был источником истины для поиска/сравнения.
     *
     * mixed, а не Uuid|null — вызывается и как self::short($this->id)
     * (свой же ID), и как self::short($otherEntity->getId()) (чужой,
     * cм. Ticket::__toString() — там же ID автора/мастера), единая точка
     * без разницы, откуда значение пришло.
     */
    public static function short(mixed $id): string
    {
        return $id !== null ? substr((string) $id, 0, 8) : '—';
    }
}
